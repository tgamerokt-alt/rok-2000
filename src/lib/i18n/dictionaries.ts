/**
 * Dictionary strings are plain data (no functions) so the whole `t` object
 * can safely cross the server -> client component boundary as a prop.
 * Parameterized strings use {placeholders} resolved with this helper.
 */
export function formatTemplate(template: string, vars: Record<string, string>): string {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => vars[key] ?? "");
}

